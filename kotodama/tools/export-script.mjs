// Exports, from the same code that renders the video:
//   story/EP01_SCRIPT.md     screenplay with timestamps
//   release/ep01.srt         subtitles (for YouTube CC / players)
//   release/chapters.txt     YouTube-style chapter list
//   player/episode.json      chapters + subtitles for the web player
import fs from 'fs';
import path from 'path';
import { ROOT } from '../src/node-env.js';
import { buildEpisode, META } from '../src/episode01/script.js';
import { CAST } from '../src/engine/characters.js';

const E = buildEpisode();
const mmss = (t) => `${Math.floor(t / 60)}:${String(Math.floor(t % 60)).padStart(2, '0')}`;
const srtT = (t) => { const ms = Math.round(t * 1000); const h = Math.floor(ms / 3600000), m = Math.floor(ms / 60000) % 60, s = Math.floor(ms / 1000) % 60; return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')},${String(ms % 1000).padStart(3, '0')}`; };
const nameOf = (id, override) => override || (id === 'narrator' ? 'NARRATOR' : (CAST[id]?.name || id));

// ---- screenplay
const out = [];
out.push(`# ${META.series}`, '', `## Episode ${META.episode}: "${META.title}" (${META.titleJp})`, '');
out.push(`**Runtime:** ${mmss(E.duration)}  ·  **Shots:** ${E.shots.length}  ·  **Dialogue lines:** ${E.subs.length}`, '');
out.push('> This screenplay is generated by `tools/export-script.mjs` from `src/episode01/*.js`, the same code that renders the video. Timestamps match the MP4.', '');
out.push('### Structure', '', '| Time | Segment | Length |', '|---|---|---|');
E.chapters.forEach((c, i) => { const end = i + 1 < E.chapters.length ? E.chapters[i + 1].t : E.duration; out.push(`| ${mmss(c.t)} | ${c.name} | ${mmss(end - c.t)} |`); });
out.push('');
let lastWho = null;
for (const e of E.script) {
  if (e.type === 'chapter') { out.push('', '---', '', `## ${e.text.toUpperCase()}  \`${mmss(e.t)}\``, ''); lastWho = null; }
  else if (e.type === 'scene') { out.push('', `### ${e.text}  \`${mmss(e.t)}\``, ''); lastWho = null; }
  else if (e.type === 'action') { out.push(`*${e.text}*`, ''); lastWho = null; }
  else if (e.type === 'line') {
    const who = nameOf(e.who, e.name).toUpperCase();
    const paren = e.style === 'shout' ? ' (shouting)' : e.style === 'think' ? ' (thinking)' : e.style === 'narr' ? ' (V.O.)' : '';
    out.push(`\`${mmss(e.t)}\` **${who}**${paren}: ${e.text}  `);
    lastWho = e.who;
  }
}
fs.mkdirSync(path.join(ROOT, 'story'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'story/EP01_SCRIPT.md'), out.join('\n') + '\n');

// ---- SRT
const srt = E.subs.map((s, i) => `${i + 1}\n${srtT(s.t0)} --> ${srtT(s.t1)}\n${s.who ? `[${nameOf(s.who, s.name)}] ` : ''}${s.text}\n`).join('\n');
fs.mkdirSync(path.join(ROOT, 'release'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'release/ep01.srt'), srt);
fs.writeFileSync(path.join(ROOT, 'story/ep01.srt'), srt);

// ---- chapters
const chapters = E.chapters.map((c) => `${mmss(c.t)} ${c.name}`).join('\n');
fs.writeFileSync(path.join(ROOT, 'release/chapters.txt'), chapters + '\n');

// ---- player data
fs.mkdirSync(path.join(ROOT, 'player'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'player/episode.json'), JSON.stringify({
  meta: META, duration: E.duration,
  chapters: E.chapters,
  subs: E.subs.map((s) => ({ t0: +s.t0.toFixed(2), t1: +s.t1.toFixed(2), who: s.who ? nameOf(s.who, s.name) : null, color: s.who ? CAST[s.who]?.color : null, text: s.text, style: s.style })),
}));
console.log(`screenplay: story/EP01_SCRIPT.md (${E.script.length} entries)\nsubtitles: release/ep01.srt + story/ep01.srt (${E.subs.length})\nchapters:\n${chapters}`);
